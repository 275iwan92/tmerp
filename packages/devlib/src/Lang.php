    public static function extend(array $dict): void
    {
        self::$extra = array_merge(self::$extra, $dict);
        self::$reverse = null;
        self::$values = [];
    }

    // Kamus aplikasi untuk browser (window.DL_DICT): fn(lang) => [teks English => terjemahan | ''].
    public static function dictUsing(?\Closure $fn): void
    {
        self::$jsDict = $fn;
    }

    public static function jsDict(): array
    {
        return self::$jsDict ? (self::$jsDict)(Locale::lang()) : [];
    }

    // Teks tampilan yang DITULIS ENGLISH (label layar/komponen, LOCKED user 2026-10-01) -> bahasa tampilan.
    // Kata DevLib sendiri dikenali dari DICT (jalan tanpa database, mis. devlib.test); selain itu lewat kamus aplikasi
    // (tmerp: sys_dictionary, yang juga mencatat teks baru otomatis). Tidak ada terjemahan -> English apa adanya.
    public static function text(?string $en): string
    {
        if ($en === null || trim($en) === '') {
            return (string) $en;
        }
        if (str_contains($en, self::RAW[0])) {
            return self::mixed($en);
        }
        $lang = Locale::lang();
        $row = $lang === 'en' ? null : self::reverse()[$en] ?? null;
        if ($row && isset($row[$lang])) {
            return $row[$lang];
        }

        return self::$translator ? (self::$translator)($en, $lang) : $en;
    }

    // NILAI DATA di dalam teks tampilan (no. dokumen, nama customer, angka, tanggal): tandai dengan raw() supaya TIDAK
    // diterjemahkan dan TIDAK tercatat di kamus -- kalau tidak, tiap dokumen yang dibuka menambah satu baris kamus.
    // Label di sekitarnya tetap ditulis English dan tetap diterjemahkan:
    //   :title="'Customer Order · '.raw($o->co_no)"   :subtitle="raw($customer.' · '.$status)"
    // Penandanya dua karakter tak terlihat (bukan objek) supaya selamat melewati prop bertipe string dan penyambungan teks;
    // text() membuangnya, jadi tidak pernah sampai ke layar. Tetap di-escape Blade seperti teks biasa (bukan HTML mentah).
    private const RAW = ["\u{2062}", "\u{2063}"];

    public static function raw(string|int|float|\Stringable|null $value): string
    {
        $s = self::plain((string) $value);

        return $s === '' ? '' : self::RAW[0].$s.self::RAW[1];
    }

    public static function hasRaw(string $text): bool
    {
        return str_contains($text, self::RAW[0]);
    }

    // Teks tanpa penanda raw(), tanpa diterjemahkan (untuk prop yang memang tidak diterjemahkan: tombol, badge).
    public static function plain(string $text): string
    {
        return str_replace(self::RAW, '', $text);
    }

    // Teks berisi raw(): bagian raw apa adanya; label di antaranya diterjemahkan tanpa tanda baca / spasi yang MENEMPEL ke
    // nilai raw ('Customer Order · ' -> kamus hanya mengenal 'Customer Order'). Tanda baca di ujung kalimat (awal / akhir
    // teks) tetap bagian label, supaya 'Saved.' tetap cocok dengan baris kamus 'Saved.'.
    private static function mixed(string $text): string
    {
        $parts = preg_split('/'.self::RAW[0].'(.*?)'.self::RAW[1].'/us', $text, -1, PREG_SPLIT_DELIM_CAPTURE);
        $last = count($parts) - 1;
        $out = '';
        foreach ($parts as $i => $part) {
            if ($i % 2) {
                $out .= $part;

                continue;
            }
            $core = self::plain($part);
            $lead = $i > 0 && preg_match('/^[^\p{L}\p{N}]+/u', $core, $m) ? $m[0] : '';
            $core = substr($core, strlen($lead));
            $trail = $i < $last && preg_match('/[^\p{L}\p{N}]+$/u', $core, $m) ? $m[0] : '';
            $core = $trail === '' ? $core : substr($core, 0, -strlen($trail));
            $out .= $lead.($core === '' ? '' : self::text($core)).$trail;
        }

        return $out;
    }

    // Teks ini HASIL terjemahan kamus DevLib untuk bahasa $lang (sisi Indonesia sebuah entri), bukan teks sumber English?
    // Dipakai kamus aplikasi supaya teks jadi yang lewat lagi di prop teks komponen tidak dicatat sebagai sumber baru.
    public static function isTranslation(string $text, string $lang): bool
    {
        if (! isset(self::$values[$lang])) {
            self::$values[$lang] = [];
            foreach (self::all() as $row) {
                $row = array_is_list($row) ? ['id' => $row[0], 'en' => $row[1]] : $row;
                if (isset($row[$lang]) && $row[$lang] !== ($row['en'] ?? null)) {
                    self::$values[$lang][$row[$lang]] = true;
                }
            }
        }

        return isset(self::$values[$lang][$text]);
    }

    private static function reverse(): array
    {
        if (self::$reverse === null) {
            self::$reverse = [];
            foreach (self::all() as $row) {
                $row = array_is_list($row) ? ['id' => $row[0], 'en' => $row[1]] : $row;
                if (isset($row['en'])) {
                    self::$reverse[$row['en']] ??= $row;
                }
            }
        }

        return self::$reverse;
    }

    public static function all(): array
    {
        return array_merge(self::DICT, self::$extra);
    }

    // Bahasa selain id/en (ja, zh, ...): teks English entri ini diterjemahkan lewat kamus aplikasi (tmerp: sys_dictionary).
    public static function translateUsing(?\Closure $fn): void
    {
        self::$translator = $fn;
    }

    // Entri = [ID, EN] atau ['id' => .., 'en' => .., 'ja' => ..]. Tidak ada terjemahan -> English.
    public static function t(string $key, ?string $fallback = null): string
    {
        $row = self::all()[$key] ?? null;
        if (! $row) {
            return $fallback ?? $key;
        }
        $lang = Locale::lang();
        $row = array_is_list($row) ? ['id' => $row[0], 'en' => $row[1]] : $row;
        $en = $row['en'] ?? reset($row);

        return $row[$lang] ?? (self::$translator ? (self::$translator)($en, $lang) : $en);
    }
