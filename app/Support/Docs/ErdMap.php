<?php

/*
 * REMARK
 * Tujuan       : Membaca bagian "Table relations" (tabel Parent | Child | Cardinality | Column | Link) di halaman sub-modul docs/tg dan menggambar diagram relasi antartabel (1:N, 1:1, N:M) sebagai SVG dengan kaki gagak, supaya relasi mudah dipahami dan tidak menyimpang dari tabelnya.
 * Sumber hulu  : docs/tg/<modul>/<sub-modul>/00_submodule_*.md (tabel adalah sumber kebenaran; FK nyata dari information_schema, relasi logis lintas-DB dari kode).
 * Input        : teks md. Cardinality: 1:N, 1:1, N:M. Link: FK (garis penuh) atau logical (garis putus-putus).
 * Output       : parse() = daftar relasi; svg() = teks SVG (teks hitam, latar putih); svgPath() = docs/tg/<modul>/img/rel-<sub-modul>.svg.
 * Dipakai oleh : php artisan docs:rw (menulis atau memeriksa), php artisan docs:check (peringatan bila hilang atau usang).
 * Status       : BARU 2026-10-17.
 */

namespace App\Support\Docs;

final class ErdMap
{
    private const W = 190;

    private const H = 34;

    private const GAP_X = 170;

    private const GAP_Y = 30;

    /**
     * @return list<array{parent: string, child: string, card: string, column: string, link: string}>|null null = no section
     */
    public static function parse(string $md): ?array
    {
        if (! preg_match('/^## Table relations\b.*?(?=^## |\z)/ms', $md, $m)) {
            return null;
        }
        $rows = [];
        foreach (preg_split('/\R/', $m[0]) as $line) {
            $line = trim($line);
            if (! str_starts_with($line, '|') || preg_match('/^\|\s*(:?-+|Parent\b)/', $line)) {
                continue;
            }
            $c = array_map('trim', explode('|', trim($line, '|')));
            if (count($c) < 5 || ! preg_match('/^`([a-z][a-z0-9_]*)`$/', $c[0], $p) || ! preg_match('/^`([a-z][a-z0-9_]*)`$/', $c[1], $q)) {
                continue;
            }
            $rows[] = ['parent' => $p[1], 'child' => $q[1], 'card' => in_array($c[2], ['1:N', '1:1', 'N:M'], true) ? $c[2] : '1:N', 'column' => trim($c[3], '` '), 'link' => strtolower($c[4]) === 'fk' ? 'fk' : 'logical'];
        }

        return $rows;
    }

    public static function svgPath(string $mdPath): string
    {
        $dir = dirname($mdPath);

        return dirname($dir).'/img/rel-'.basename($dir).'.svg';
    }

    public static function svg(array $rels, string $source): string
    {
        // Level = longest chain from a root; self relations and cycle-closing edges do not count.
        $nodes = [];
        foreach ($rels as $r) {
            $nodes[$r['parent']] = $nodes[$r['child']] = 0;
        }
        for ($pass = 0; $pass < count($nodes); $pass++) {
            foreach ($rels as $r) {
                if ($r['parent'] !== $r['child'] && $nodes[$r['child']] <= $nodes[$r['parent']] && $nodes[$r['parent']] < count($nodes) - 1) {
                    $nodes[$r['child']] = $nodes[$r['parent']] + 1;
                }
            }
        }
        // A table nobody points to (a master) sits right before its nearest child instead of in the far left column.
        $hasParent = [];
        foreach ($rels as $r) {
            if ($r['parent'] !== $r['child']) {
                $hasParent[$r['child']] = true;
            }
        }
        foreach (array_keys($nodes) as $n) {
            if (! isset($hasParent[$n])) {
                $kids = array_map(fn ($r) => $nodes[$r['child']], array_filter($rels, fn ($r) => $r['parent'] === $n && $r['child'] !== $n));
                $nodes[$n] = $kids ? max(0, min($kids) - 1) : 0;
            }
        }        $cols = [];
        foreach ($nodes as $name => $lvl) {
            $cols[$lvl][] = $name;
        }
        ksort($cols);
        $cols = self::untangle(array_values($cols), $rels);
        $pos = [];
        $maxRows = max(1, ...array_map('count', $cols ?: [[0]]));
        foreach (array_values($cols) as $ci => $names) {
            $offset = (($maxRows - count($names)) * (self::H + self::GAP_Y)) / 2;
            foreach ($names as $ri => $name) {
                $pos[$name] = [20 + $ci * (self::W + self::GAP_X), 50 + $offset + $ri * (self::H + self::GAP_Y)];
            }
        }
        $w = 40 + count($cols) * (self::W + self::GAP_X) - self::GAP_X;
        $h = 90 + $maxRows * (self::H + self::GAP_Y);
        $e = fn (string $s) => htmlspecialchars($s, ENT_XML1);
        $o = "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 $w $h\" font-family=\"sans-serif\" font-size=\"11\">\n";
        $o .= '  <!-- Generated by php artisan docs:rw from '.$e($source).'. Do not edit: change the Table relations table and run the command again. -->'."\n";
        $o .= "  <rect width=\"$w\" height=\"$h\" fill=\"#fff\"/>\n  <g stroke=\"#000\" stroke-width=\"1.2\" fill=\"none\">\n";
        $labels = '';
        foreach ($rels as $r) {
            [$px, $py] = $pos[$r['parent']];
            [$cx, $cy] = $pos[$r['child']];
            $dash = $r['link'] === 'fk' ? '' : ' stroke-dasharray="6 4"';
            if ($r['parent'] === $r['child']) {
                $x = $px + self::W;
                $y = $py + self::H / 2;
                $o .= "    <path d=\"M$x,".($y - 6).' h26 v22 h-'.(self::W - 20).' v-'.(self::H / 2 + 2).'"'.$dash." />\n";
                $labels .= '<text x="'.($x + 30).'" y="'.($y + 12).'">'.$e($r['column'])."</text>\n";

                continue;
            }
            $forward = $cx > $px;
            $x1 = $forward ? $px + self::W : $px;
            $x2 = $forward ? $cx : $cx + self::W;
            $y1 = $py + self::H / 2;
            $y2 = $cy + self::H / 2;
            $o .= "    <line x1=\"$x1\" y1=\"$y1\" x2=\"$x2\" y2=\"$y2\"$dash />\n";
            $o .= self::end($x1, $y1, $forward ? 1 : -1, $r['card'] === '1:N' || $r['card'] === '1:1' ? 'one' : 'many');
            $o .= self::end($x2, $y2, $forward ? -1 : 1, $r['card'] === '1:1' ? 'one' : 'many');
            $labels .= '<rect x="'.(($x1 + ($x2 - $x1) * 0.62) - 3 * strlen($r['column']) - 2).'" y="'.(($y1 + ($y2 - $y1) * 0.62) - 18).'" width="'.(6 * strlen($r['column']) + 4).'" height="13" fill="#fff" stroke="none"/><text x="'.(($x1 + ($x2 - $x1) * 0.62)).'" y="'.(($y1 + ($y2 - $y1) * 0.62) - 8).'" text-anchor="middle">'.$e($r['column']).($r['card'] === 'N:M' ? ' (N:M)' : '')."</text>\n";
        }
        $o .= "  </g>\n  <g fill=\"#000\">\n    ".$labels;
        foreach ($pos as $name => [$x, $y]) {
            $o .= "    <rect x=\"$x\" y=\"$y\" width=\"".self::W.'" height="'.self::H.'" rx="6" fill="#dbeafe" stroke="#000" stroke-width="1.2"/>'."\n";
            $o .= '    <text x="'.($x + self::W / 2).'" y="'.($y + 21).'" text-anchor="middle" font-family="monospace" font-size="12" font-weight="bold">'.$e($name)."</text>\n";
        }
        $o .= "  </g>\n";
        $ly = $h - 14;
        $o .= '  <g fill="#000"><text x="20" y="'.$ly.'">Solid line = real foreign key. Dashed line = logical link (no foreign key, matched in code). Bar = one, crow\'s foot = many.</text></g>'."\n</svg>\n";

        return $o;
    }

    // Barycenter sweeps: order the tables inside each level by the average position of their neighbours, so lines cross less.
    private static function untangle(array $cols, array $rels): array
    {
        $y = [];
        foreach ($cols as $names) {
            foreach ($names as $i => $n) {
                $y[$n] = ($i + 0.5) / count($names);
            }
        }
        $neighbours = [];
        foreach ($rels as $r) {
            if ($r['parent'] !== $r['child']) {
                $neighbours[$r['child']][] = $r['parent'];
                $neighbours[$r['parent']][] = $r['child'];
            }
        }
        for ($sweep = 0; $sweep < 6; $sweep++) {
            foreach ($sweep % 2 ? array_reverse(array_keys($cols)) : array_keys($cols) as $ci) {
                $avg = fn ($n) => ($ns = $neighbours[$n] ?? []) ? array_sum(array_map(fn ($x) => $y[$x], $ns)) / count($ns) : $y[$n];
                usort($cols[$ci], fn ($a, $b) => $avg($a) <=> $avg($b));
                foreach ($cols[$ci] as $i => $n) {
                    $y[$n] = ($i + 0.5) / count($cols[$ci]);
                }
            }
        }

        return $cols;
    }

    // Line end marker: a bar for "one", a crow's foot for "many"; $dir = +1 when the line leaves to the right.
    private static function end(float $x, float $y, int $dir, string $kind): string
    {
        if ($kind === 'one') {
            $b = $x + 10 * $dir;

            return "    <line x1=\"$b\" y1=\"".($y - 7).'" x2="'.$b.'" y2="'.($y + 7)."\"/>\n";
        }
        $t = $x + 12 * $dir;

        return "    <line x1=\"$t\" y1=\"$y\" x2=\"$x\" y2=\"".($y - 7)."\"/>\n    <line x1=\"$t\" y1=\"$y\" x2=\"$x\" y2=\"".($y + 7)."\"/>\n    <line x1=\"$t\" y1=\"$y\" x2=\"$x\" y2=\"$y\"/>\n";
    }
}
